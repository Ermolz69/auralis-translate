import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { digest } from './flores-file-fixture.mjs';
import { readRunSnapshot } from './cli-run-state.mjs';

const root = path.resolve('.');
const workspace = path.join(root, '.cache/eval/commons-asus-full-1_8b-v1/run-M5lG2W');
const source = fs.readFileSync(path.join(root, '.cache/eval/commons-asus-rog-ally-892592485/source.zh.srt'));
assert.equal(digest(source), '923aed3991c2308d92b89c45181cea8ec7ece74e9b4d3a3ce0234d95e329913b');
const reportBytes = fs.readFileSync(path.join(workspace, 'report.json'));
assert.equal(digest(reportBytes), '5f606c5f3e66acf4c20a162101cede8f95381145fc6c55a5da98dd5c912a066e');
const report = JSON.parse(reportBytes);
assert.equal(report.experiment, 'commons-asus-full-1_8b-v1');
assert.equal(report.status, 'failed');
assert.equal(report.revision, '2d20f8accf8dea4e1b93d63155dac5d14d8632de');
assert.equal(report.source_cues, 268);
assert.equal(report.profile_sha256, '432a1b064397a96334d777dfa01a2cef58d367b37023f1f9175501969698df4d');
assert.equal(report.cli_sha256, '82df0fbd0167b9163f945c58d8387a1edf2c6eedfed9f38086f617f74914df1d');
assert.equal(report.runtime_sha256, '6f15be27bd80b6b4d52afefa49094e18fcfab55d5da354d717971f2d2537b2f4');
assert.equal(report.model_sha256_verified_by_doctor, 'dc5f44fcf1fa496ee7ad725982c0c8c553a4de00259b53af84c4b89fb0c06699');
assert.equal(report.requests.length, 63);
const chats = report.requests.filter(row => row.path === '/v1/chat/completions');
assert.equal(chats.length, 20);
const failed = chats.at(-1);
assert.equal(failed.request_sha256, 'c4fb7132f0ab385aad7d3cef404a9f9fc772169a221d5d492873fffc9378b1c3');
assert.equal(digest(Buffer.from(failed.raw_response)), 'b72860ab2dd8fb201fd983b47bd3767e240d0656cb561fa442b0eb063d989459');
assert.equal(digest(Buffer.from(failed.raw_candidate)), '99741e4535992e660cb14d1132527cf34a7661a6114e9601c98625e48c7c8b31');
assert.equal(JSON.parse(failed.raw_response).choices[0].finish_reason, 'stop');
assert.equal(failed.usage.prompt_tokens, 279);
assert.equal(failed.usage.completion_tokens, 52);
const envelope = JSON.parse(failed.request.messages[0].content.split('Input JSON:\n')[1]);
assert.equal(envelope.target_slots[0].segment_id, 20);
assert.deepEqual(envelope.source_context.map(row => row.segment_id), [19, 21]);
const [translation] = JSON.parse(failed.raw_candidate).translations;
assert.equal(translation.segment_id, 21);
assert.equal(translation.line_index, 0);
const blocks = source.toString('utf8').trimEnd().split(/\n\n+/u);
assert.equal(blocks.length, 268);
assert.equal(digest(Buffer.from(blocks.slice(18, 21).join('\n\n'))),
  'c1a1eb9346f4120673f524dbfe0d89fb3220a18261db6d4aaaefa2154d3fc83a');
const database = path.join(workspace, 'state/auralis-translate.sqlite');
const snapshot = readRunSnapshot(database, 'b1b22de2-f3c6-431f-889d-bf9fa6300552');
assert(snapshot.run);
assert.equal(snapshot.checkpoints.length, 19);
assert(snapshot.checkpoints.every((row, index) => row.block_index === index));
assert.equal(snapshot.attempts.length, 1);
assert.equal(snapshot.results.length, 0);
assert.equal(digest(fs.readFileSync(database)), '3281d3dded0ecf87dcee8c68741bd4f005f86ac44969c00a05dfc66f8e8187a1');
assert(!fs.existsSync(path.join(workspace, 'candidate.ru.srt')));
assert.match(report.failures.at(-1).message, /v5 response changed target slot identity/u);
console.log('ASUS 1.8B private failure verified: 19/268 checkpoints, wrong next-cue ID, zero results/output.');
