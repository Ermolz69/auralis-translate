import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');
const read = async file => fs.readFile(path.join(root, file));
const summary = JSON.parse(await read('eval/reports/commons-wikipedia-lesson-source-v1.json'));
const inventory = JSON.parse(await read('eval/corpora/commons-wikipedia-lesson-candidate-v1.json'));
const original = await read('.cache/eval/commons-wikipedia-lesson-caption/attempt-joeurN/source.zh.srt');
const derivative = await read(inventory.sources[0].local_candidate_path);
const media = await read('.cache/eval/commons-wikipedia-lesson-media/attempt-UGi9xp/source.ogv');
const mediaCheck = JSON.parse(await read('.cache/eval/commons-wikipedia-lesson-media/attempt-UGi9xp/media-check.json'));
const acquisition = await read('.cache/eval/commons-wikipedia-lesson-caption/attempt-joeurN/acquisition.json');
const derivation = await read('.cache/eval/commons-wikipedia-lesson-caption/derived-v1/derivation.json');
const mediaAcquisition = await read('.cache/eval/commons-wikipedia-lesson-media/attempt-UGi9xp/acquisition.json');
const privateMediaCheck = await read('.cache/eval/commons-wikipedia-lesson-media/attempt-UGi9xp/media-check.json');
assert.equal(summary.caption_original_sha256, sha256(original));
assert.equal(summary.caption_derivative_sha256, sha256(derivative));
assert.equal(summary.caption_derivative_sha256, inventory.sources[0].sha256);
assert.equal(summary.caption_cues, inventory.sources[0].cue_count);
assert.equal(summary.changed_timing_fields,
  JSON.parse(derivation).changed_timing_count);
assert.equal(summary.media_sha256, sha256(media));
assert.equal(summary.media_bytes, media.length);
assert.equal(summary.media_duration_ms, mediaCheck.coverage.media_duration_ms);
assert.equal(summary.media_duration_ms, inventory.sources[0].media_duration_ms);
assert.equal(summary.last_cue_end_ms, mediaCheck.coverage.max_end_ms);
assert.equal(summary.cue_overrun_count, mediaCheck.coverage.overrun_count);
assert.equal(summary.private_acquisition_sha256, sha256(acquisition));
assert.equal(summary.private_derivation_sha256, sha256(derivation));
assert.equal(summary.private_media_acquisition_sha256, sha256(mediaAcquisition));
assert.equal(summary.private_media_check_sha256, sha256(privateMediaCheck));
assert.equal(summary.human_bilingual_review_count, 0);
assert.equal(summary.eligible_cues_added, 0);
assert.equal(inventory.sources[0].rights.subtitle.decision, 'unknown');
console.log('Wikipedia lesson public report matched immutable private caption, media, mapping and non-admission.');
